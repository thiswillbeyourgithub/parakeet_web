"""Write the ORT reduced-build operator config (--include_ops_by_config) for a set of models.

Usage:
    uv run scripts/ort-custom/make-ops-config.py OUT.config MODEL.onnx [MODEL.onnx ...]

Why not ORT's own tools/python/create_reduced_build_config.py: it only sees the ops written in
the .onnx files, but the app runs sessions at graphOptimizationLevel 'all', whose fusions
replace those ops with contrib kernels (FusedConv, SkipLayerNormalization, MatMulIntegerToFloat,
...) that must also be compiled in. A kernel missing from a reduced build fails session creation
with "Could not find an implementation", so this keeps the union of:
  1. the ops as written (graph only, external weights are not loaded), and
  2. the ops of each model after ORT's EXTENDED and ALL optimizers (the onnxruntime pin must
     match the ORT version being built, the fusions are version dependent).
NCHWc ops are dropped: that layout rewrite only exists on x86 MLAS, never on WASM.

The union is a superset by design, a few unused kernels cost bytes, a missing one breaks a model.
Verify the result by creating a session for every model with the built runtime.

Written with the help of Claude Code.
"""
import collections
import glob
import os
import sys
import tempfile

import onnx
import onnxruntime as ort

ops = collections.defaultdict(set)


def add_graph(graph, versions):
    for node in graph.node:
        if node.domain == "com.microsoft.nchwc":
            continue
        ops[(node.domain or "ai.onnx", versions.get(node.domain, 1))].add(node.op_type)
        for attr in node.attribute:
            for sub in [attr.g] if attr.HasField("g") else list(attr.graphs):
                add_graph(sub, versions)


def add_model(path):
    model = onnx.load(path, load_external_data=False)
    add_graph(model.graph, {o.domain: o.version for o in model.opset_import})


def main():
    out, models = sys.argv[1], sys.argv[2:]
    if not models:
        sys.exit(__doc__)
    with tempfile.TemporaryDirectory() as tmp:
        for path in models:
            add_model(path)
            for level in (ort.GraphOptimizationLevel.ORT_ENABLE_EXTENDED, ort.GraphOptimizationLevel.ORT_ENABLE_ALL):
                opts = ort.SessionOptions()
                opts.graph_optimization_level = level
                opts.log_severity_level = 3
                opts.optimized_model_filepath = os.path.join(tmp, "opt.onnx")
                # Keep weights out of the protobuf, so a >2 GB encoder can still be serialized.
                opts.add_session_config_entry("session.optimized_model_external_initializers_file_name", "opt.onnx.data")
                opts.add_session_config_entry("session.optimized_model_external_initializers_min_size_in_bytes", "1024")
                ort.InferenceSession(os.path.realpath(path), opts, providers=["CPUExecutionProvider"])
                add_model(opts.optimized_model_filepath)
                for f in glob.glob(os.path.join(tmp, "opt.onnx*")):
                    os.remove(f)
            print(f"[ops] {path}", file=sys.stderr, flush=True)
    with open(out, "w") as f:
        f.write("# Generated by scripts/ort-custom/make-ops-config.py, do not edit by hand.\n")
        for (domain, version), names in sorted(ops.items()):
            f.write(f"{domain};{version};{','.join(sorted(names))}\n")
    print(f"[ops] {sum(len(n) for n in ops.values())} ops -> {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
